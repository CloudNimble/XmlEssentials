using System;
using System.Collections.Generic;
using System.Text;

namespace CloudNimble.XmlEssentials.SourceGeneration
{

    /// <summary>
    /// Emits a generated <c>XmlSerializerContext</c> partial class.
    /// </summary>
    internal static class ContextEmitter
    {

        #region Public Methods

        /// <summary>
        /// Emits the generated source for <paramref name="context"/>.
        /// </summary>
        /// <param name="context">The context spec.</param>
        /// <returns>The C# source.</returns>
        internal static string Emit(ContextSpec context)
        {
            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8625");
            builder.AppendLine("using System;");
            builder.AppendLine("using CloudNimble.Text.Xml;");
            builder.AppendLine("using CloudNimble.Text.Xml.Serialization;");
            builder.AppendLine();
            if (!string.IsNullOrEmpty(context.Namespace))
            {
                builder.Append("namespace ").Append(context.Namespace);
                builder.AppendLine();
                builder.AppendLine("{");
                builder.AppendLine();
            }

            var indent = string.IsNullOrEmpty(context.Namespace) ? "" : "    ";
            if (context.EmitInheritance)
            {
                foreach (var type in context.Types)
                {
                    // A type the runtime library reads and writes is found through GetTypeInfo. It is not a root.
                    if (type.Kind == 5)
                    {
                        continue;
                    }

                    builder.Append(indent).Append("[XmlSerializable<").Append(type.ClrTypeName).AppendLine(">]");
                }
            }

            builder.Append(indent).Append(context.Accessibility).Append(" partial class ").Append(context.Name);
            if (context.EmitInheritance)
            {
                builder.Append(" : XmlSerializerContext, IXmlTypeInfoResolver");
            }
            else
            {
                // The context answers the resolver interface itself, so that it can answer for the options that ask.
                builder.Append(" : IXmlTypeInfoResolver");
            }

            builder.AppendLine();
            builder.Append(indent).AppendLine("{");
            builder.AppendLine();
            builder.Append(indent).Append("    private static readonly ").Append(context.Name).Append(" s_default = new ").Append(context.Name).AppendLine("(null);");
            builder.AppendLine();
            builder.Append(indent).Append("    /// <summary>").AppendLine();
            builder.Append(indent).Append("    /// Gets the default context, seeded from [XmlSourceGenerationOptions] when present.").AppendLine();
            builder.Append(indent).Append("    /// </summary>").AppendLine();
            builder.Append(indent).Append("    public static ").Append(context.Name).AppendLine(" Default => s_default;");
            builder.AppendLine();
            foreach (var type in context.Types)
            {
                builder.Append(indent).Append("    private XmlTypeInfo<").Append(type.ClrTypeName).Append(">? _").Append(type.PropertyName).AppendLine(";");
            }

            builder.AppendLine();
            var registrations = new List<string>();
            foreach (var type in context.Types)
            {
                if (ShapeRegistration(type) is { } registration)
                {
                    registrations.Add(registration);
                }
            }

            if (registrations.Count > 0)
            {
                // The runtime library asks whether a member's type is a collection or a dictionary while it binds
                // the type that has the member, before it has asked for the type info of the member's type. The
                // context names those types here, so the answer is known without reading their interfaces.
                builder.Append(indent).Append("    static ").Append(context.Name).AppendLine("()");
                builder.Append(indent).AppendLine("    {");
                foreach (var registration in registrations)
                {
                    builder.Append(indent).Append("        ").AppendLine(registration);
                }

                builder.Append(indent).AppendLine("    }");
                builder.AppendLine();
            }

            builder.Append(indent).Append("    /// <summary>").AppendLine();
            builder.Append(indent).Append("    /// Creates a context seeded from [XmlSourceGenerationOptions].").AppendLine();
            builder.Append(indent).Append("    /// </summary>").AppendLine();
            builder.Append(indent).Append("    public ").Append(context.Name).AppendLine("() : this(null)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).Append("    /// <summary>").AppendLine();
            builder.Append(indent).Append("    /// Creates a context with <paramref name=\"options\"/>. Constructor options win over [XmlSourceGenerationOptions].").AppendLine();
            builder.Append(indent).Append("    /// </summary>").AppendLine();
            builder.Append(indent).Append("    /// <param name=\"options\">The options, or null to apply the source-generation seed.</param>").AppendLine();
            builder.Append(indent).Append("    public ").Append(context.Name).AppendLine("(XmlSerializerOptions? options) : base(Apply(options))");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            foreach (var type in context.Types)
            {
                builder.Append(indent).Append("    /// <summary>").AppendLine();
                builder.Append(indent).Append("    /// Gets type info for <see cref=\"").Append(type.ClrTypeName).Append("\"/>.").AppendLine();
                builder.Append(indent).Append("    /// </summary>").AppendLine();
                builder.Append(indent).Append(type.Kind == 5 ? "    private XmlTypeInfo<" : "    public XmlTypeInfo<").Append(type.ClrTypeName).Append("> ").Append(type.PropertyName).AppendLine();
                builder.Append(indent).AppendLine("    {");
                builder.Append(indent).AppendLine("        get");
                builder.Append(indent).AppendLine("        {");
                builder.Append(indent).Append("            return _").Append(type.PropertyName).Append(" ??= ");
                builder.Append(CreateExpression(type, "Options")).Append(';');

                builder.AppendLine();
                builder.Append(indent).AppendLine("        }");
                builder.Append(indent).AppendLine("    }");
                builder.AppendLine();
            }

            builder.Append(indent).AppendLine("    /// <inheritdoc />");
            builder.Append(indent).AppendLine("    public override XmlTypeInfo? GetTypeInfo(Type type)");
            builder.Append(indent).AppendLine("    {");
            foreach (var type in context.Types)
            {
                builder.Append(indent).Append("        if (type == typeof(").Append(type.ClrTypeName).Append(")) return ").Append(type.PropertyName).AppendLine(";");
            }

            // A type the context neither lists nor reaches is answered only when its converter exists already. Anything else
            // is left to the next resolver, so the context never maps the members of a type through reflection.
            builder.Append(indent).AppendLine("        return XmlMetadataServices.GetBuiltInTypeInfo(type, Options);");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            // Other options ask when the context is one of several resolvers. Type info belongs to the options
            // it was created for, so each type is created again for the options that ask; they keep it.
            builder.Append(indent).AppendLine("    /// <inheritdoc />");
            builder.Append(indent).AppendLine("    XmlTypeInfo? IXmlTypeInfoResolver.GetTypeInfo(Type type, XmlSerializerOptions options)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        if (ReferenceEquals(options, Options)) return GetTypeInfo(type);");
            foreach (var type in context.Types)
            {
                builder.Append(indent).Append("        if (type == typeof(").Append(type.ClrTypeName).Append(")) return ").Append(CreateExpression(type, "options")).AppendLine(";");
            }

            builder.Append(indent).AppendLine("        return XmlMetadataServices.GetBuiltInTypeInfo(type, options);");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("    private static XmlSerializerOptions Apply(XmlSerializerOptions? options)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        if (options is not null)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            return options;");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        var seeded = new XmlSerializerOptions();");
            if (context.Options.HasSeed)
            {
                if (context.Options.WriteIndented)
                {
                    builder.Append(indent).AppendLine("        seeded.WriteIndented = true;");
                }

                if (context.Options.OmitXmlDeclaration)
                {
                    builder.Append(indent).AppendLine("        seeded.OmitXmlDeclaration = true;");
                }

                if (!string.IsNullOrEmpty(context.Options.DefaultNamespace))
                {
                    builder.Append(indent).Append("        seeded.DefaultNamespace = \"").Append(Escape(context.Options.DefaultNamespace)).AppendLine("\";");
                }

                EmitNaming(builder, indent, "PropertyNamingPolicy", context.Options.PropertyNamingPolicy);
                EmitNaming(builder, indent, "ElementNamingPolicy", context.Options.ElementNamingPolicy);
                EmitNaming(builder, indent, "AttributeNamingPolicy", context.Options.AttributeNamingPolicy);
                if (context.Options.IncludeFields)
                {
                    builder.Append(indent).AppendLine("        seeded.IncludeFields = true;");
                }

                if (context.Options.RespectNullableAnnotations)
                {
                    builder.Append(indent).AppendLine("        seeded.RespectNullableAnnotations = true;");
                }

                if (context.Options.PreferredObjectCreationHandling != 0)
                {
                    builder.Append(indent).Append("        seeded.PreferredObjectCreationHandling = (XmlObjectCreationHandling)").Append(context.Options.PreferredObjectCreationHandling).AppendLine(";");
                }

                if (context.Options.UnknownTypeHandling != 0)
                {
                    builder.Append(indent).Append("        seeded.UnknownTypeHandling = (XmlUnknownTypeHandling)").Append(context.Options.UnknownTypeHandling).AppendLine(";");
                }

                if (context.Options.EmitByteOrderMark)
                {
                    builder.Append(indent).AppendLine("        seeded.EmitByteOrderMark = true;");
                }

                if (context.Options.EnumHandling != 0)
                {
                    builder.Append(indent).Append("        seeded.EnumHandling = (XmlEnumHandling)").Append(context.Options.EnumHandling).AppendLine(";");
                }

                // The write fast path writes every member it was compiled with, so it is not used with options that
                // leave read-only members out: the serializer writes from the metadata then.
                if (context.Options.IgnoreReadOnlyFields)
                {
                    builder.Append(indent).AppendLine("        seeded.IgnoreReadOnlyFields = true;");
                }

                if (context.Options.IgnoreReadOnlyProperties)
                {
                    builder.Append(indent).AppendLine("        seeded.IgnoreReadOnlyProperties = true;");
                }

                if (context.Options.MaxDepth != 0)
                {
                    builder.Append(indent).Append("        seeded.MaxDepth = ").Append(context.Options.MaxDepth).AppendLine(";");
                }

                if (context.Options.PropertyNameCaseInsensitive)
                {
                    builder.Append(indent).AppendLine("        seeded.PropertyNameCaseInsensitive = true;");
                }

                if (context.Options.MemberOrder != 0)
                {
                    builder.Append(indent).Append("        seeded.MemberOrder = (XmlMemberOrder)").Append(context.Options.MemberOrder).AppendLine(";");
                }

                if (context.Options.CharHandling != 0)
                {
                    builder.Append(indent).Append("        seeded.CharHandling = (XmlCharHandling)").Append(context.Options.CharHandling).AppendLine(";");
                }

                if (context.Options.UtcOffsetHandling != 0)
                {
                    builder.Append(indent).Append("        seeded.UtcOffsetHandling = (XmlUtcOffsetHandling)").Append(context.Options.UtcOffsetHandling).AppendLine(";");
                }

                if (context.Options.DefaultCollectionMapping != 0)
                {
                    builder.Append(indent).Append("        seeded.DefaultCollectionMapping = (XmlCollectionMapping)").Append(context.Options.DefaultCollectionMapping).AppendLine(";");
                }

                if (context.Options.XmlVersion != 0)
                {
                    builder.Append(indent).Append("        seeded.XmlVersion = (XmlVersion)").Append(context.Options.XmlVersion).AppendLine(";");
                }

                // The write fast path reads the ignore condition from the options when it runs, and it is used only
                // when the mapping of the options is the one it was compiled for, so the seed sets both.
                if (context.Options.DefaultIgnoreCondition != 0)
                {
                    builder.Append(indent).Append("        seeded.DefaultIgnoreCondition = (XmlIgnoreCondition)").Append(context.Options.DefaultIgnoreCondition).AppendLine(";");
                }

                if (context.Options.DefaultPropertyMapping != 0)
                {
                    builder.Append(indent).Append("        seeded.DefaultPropertyMapping = (XmlPropertyMapping)").Append(context.Options.DefaultPropertyMapping).AppendLine(";");
                }
            }

            builder.Append(indent).AppendLine("        return seeded;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            EmitFastPathTest(builder, indent, context);

            // A number that is not finite is refused when NumberHandling is Strict, as the built-in converters refuse it.
            foreach (var number in new[] { "float", "double" })
            {
                builder.Append(indent).Append("    private static ").Append(number).Append(" __Finite(").Append(number).AppendLine(" value, XmlSerializerOptions options)");
                builder.Append(indent).AppendLine("    {");
                builder.Append(indent).Append("        if (options.NumberHandling is XmlNumberHandling.Strict && !").Append(number).AppendLine(".IsFinite(value))");
                builder.Append(indent).AppendLine("        {");
                builder.Append(indent).AppendLine("            throw XmlMetadataServices.CreateException(\"Named floating-point literals are not allowed when NumberHandling is Strict.\");");
                builder.Append(indent).AppendLine("        }");
                builder.AppendLine();
                builder.Append(indent).AppendLine("        return value;");
                builder.Append(indent).AppendLine("    }");
                builder.AppendLine();
            }

            // The type info of a member's type is the same for every object read with the same options, so it
            // is resolved once and kept. The pair is replaced as one object, so a reader never sees the
            // type info of one options instance next to another.
            builder.Append(indent).AppendLine("    private sealed class __Held<T>");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        internal static __Held<T>? Last;");
            builder.Append(indent).AppendLine("        internal readonly XmlSerializerOptions Options;");
            builder.Append(indent).AppendLine("        internal readonly XmlTypeInfo<T> Info;");
            builder.Append(indent).AppendLine("        internal __Held(XmlSerializerOptions options, XmlTypeInfo<T> info)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            Options = options;");
            builder.Append(indent).AppendLine("            Info = info;");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            var usesPropertyHelper = false;
            foreach (var type in context.Types)
            {
                usesPropertyHelper |= type.Metadata.Contains("__Property(");
            }

            if (usesPropertyHelper)
            {
                // The classes a schema generates have public properties with a getter and a setter. Their metadata
                // is written before the classes exist as symbols, so the property type is inferred here.
                builder.Append(indent).AppendLine("    private static XmlPropertyInfoValues<TDeclaring, TValue> __Property<TDeclaring, TValue>(string name, Func<TDeclaring, TValue> get, Action<TDeclaring, TValue> set, params Attribute[] attributes)");
                builder.Append(indent).AppendLine("        where TDeclaring : class");
                builder.Append(indent).AppendLine("    {");
                builder.Append(indent).AppendLine("        return new XmlPropertyInfoValues<TDeclaring, TValue>");
                builder.Append(indent).AppendLine("        {");
                builder.Append(indent).AppendLine("            PropertyName = name,");
                builder.Append(indent).AppendLine("            Getter = get,");
                builder.Append(indent).AppendLine("            Setter = (ref TDeclaring obj, TValue value) => set(obj, value),");
                builder.Append(indent).AppendLine("            Attributes = attributes,");
                builder.Append(indent).AppendLine("        };");
                builder.Append(indent).AppendLine("    }");
                builder.AppendLine();
            }

            builder.Append(indent).AppendLine("    private static XmlTypeInfo<T> __GetInfo<T>(XmlSerializerOptions options)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        var held = __Held<T>.Last;");
            builder.Append(indent).AppendLine("        if (held is null || !ReferenceEquals(held.Options, options))");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            held = new __Held<T>(options, options.GetTypeInfo<T>());");
            builder.Append(indent).AppendLine("            __Held<T>.Last = held;");
            builder.Append(indent).AppendLine("        }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("        return held.Info;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            foreach (var type in context.Types)
            {
                if (type.EmitSerialization)
                {
                    ConverterEmitter.Emit(builder, indent, type);
                }
            }

            foreach (var type in context.Types)
            {
                if (type.Metadata.Length > 0)
                {
                    EmitMetadata(builder, indent, type);
                }
            }

            builder.Append(indent).AppendLine("}");
            if (!string.IsNullOrEmpty(context.Namespace))
            {
                builder.AppendLine();
                builder.AppendLine("}");
            }

            return builder.ToString();
        }

        #endregion

        #region Private Methods

        /// <summary>
        /// Emits an assignment of a known naming policy when <paramref name="policy"/> is not unspecified.
        /// </summary>
        /// <param name="builder">The source.</param>
        /// <param name="indent">The indent.</param>
        /// <param name="property">The options property name.</param>
        /// <param name="policy">The policy value.</param>
        internal static void EmitNaming(StringBuilder builder, string indent, string property, int policy)
        {
            var value = NamingPolicy(policy);
            if (value is null)
            {
                return;
            }

            builder.Append(indent).Append("        seeded.").Append(property).Append(" = ").Append(value).AppendLine(";");
        }

        /// <summary>
        /// Emits the method that says whether the write fast path may be used with the options a type info is for.
        /// </summary>
        /// <param name="builder">The source.</param>
        /// <param name="indent">The type indent.</param>
        /// <param name="context">The context.</param>
        /// <remarks>
        /// The fast path has the names and the choice of members compiled in, and writes the scalar types named
        /// here without a converter. With options that ask for something else it is not used, and the runtime
        /// library writes from the metadata, which follows every option.
        /// </remarks>
        internal static void EmitFastPathTest(StringBuilder builder, string indent, ContextSpec context)
        {
            var direct = new System.Collections.Generic.List<string>();
            foreach (var type in context.Types)
            {
                if (!type.EmitSerialization)
                {
                    continue;
                }

                foreach (var member in type.Members)
                {
                    var name = member.IsCollection ? member.ItemTypeName : member.ClrTypeName;
                    var core = name.EndsWith("?", System.StringComparison.Ordinal) ? name.Substring(0, name.Length - 1) : name;
                    if (ConverterEmitter.IsLeafScalar(core) && !direct.Contains(core))
                    {
                        direct.Add(core);
                    }
                }
            }

            // The fast path has the names and the choice of members compiled in. It is used only with options that
            // agree with them; with any others the runtime library writes from the metadata.
            builder.Append(indent).AppendLine("    private static bool __CanUseFastPath<T>(XmlSerializerOptions options)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).Append("        return XmlMetadataServices.CanUseSerializeHandler(options, ")
                .Append(NamingPolicy(TypeGraphWalker.ElementPolicy(context.Options)) ?? "null").Append(", ")
                .Append(NamingPolicy(TypeGraphWalker.AttributePolicy(context.Options)) ?? "null").Append(", ")
                .Append("(XmlPropertyMapping)").Append(context.Options.DefaultPropertyMapping).Append(", ")
                .Append("(XmlCollectionMapping)").Append(context.Options.DefaultCollectionMapping).Append(", ")
                .Append(context.Options.IncludeFields ? "true" : "false")
                .Append(", typeof(T)");
            foreach (var name in direct)
            {
                builder.Append(", typeof(").Append(name).Append(')');
            }

            builder.AppendLine(");");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
        }

        /// <summary>
        /// Emits the method that creates the type info of an object type from its metadata, and the accessors it calls.
        /// </summary>
        /// <param name="builder">The source.</param>
        /// <param name="indent">The indent of the context class.</param>
        /// <param name="type">An object type with metadata.</param>
        internal static void EmitMetadata(StringBuilder builder, string indent, TypeSpec type)
        {
            builder.AppendLine();
            foreach (var line in type.Accessors.Split('\n'))
            {
                var text = line.TrimEnd('\r');
                if (text.Length > 0)
                {
                    builder.Append(indent).Append("    ").AppendLine(text);
                }
            }

            builder.Append(indent).Append("    private static XmlTypeInfo<").Append(type.ClrTypeName).Append("> __Create_").Append(type.PropertyName).AppendLine("(XmlSerializerOptions options)");
            builder.Append(indent).AppendLine("    {");

            // The fast path is handed over only when the options are the ones it was compiled for.
            var handler = type.EmitSerialization
                ? "SerializeHandler = __CanUseFastPath<" + type.ClrTypeName + ">(options) ? __Serialize_" + type.PropertyName + " : null,"
                : null;
            if (!type.EmitMetadata)
            {
                // Serialization mode: the type has a write fast path and no metadata, so it cannot be read, and it
                // can be written only with the options the fast path was compiled for.
                builder.Append(indent).Append("        return XmlMetadataServices.CreateObjectInfo(options, new XmlObjectInfoValues<").Append(type.ClrTypeName).Append("> { ").Append(handler).AppendLine(" });");
                builder.Append(indent).AppendLine("    }");
                return;
            }

            foreach (var line in type.Metadata.Split('\n'))
            {
                var text = line.TrimEnd('\r');
                if (text == MetadataBuilder.HandlerLine)
                {
                    if (handler is not null)
                    {
                        builder.Append(indent).Append("            ").AppendLine(handler);
                    }

                    continue;
                }

                if (text.Length > 0)
                {
                    builder.Append(indent).Append("        ").AppendLine(text);
                }
            }

            builder.Append(indent).AppendLine("    }");
        }

        /// <summary>
        /// Returns the expression that creates type info for <paramref name="type"/>, bound to the given options.
        /// </summary>
        /// <param name="type">The type spec.</param>
        /// <param name="options">The expression for the options: the context's own, or the ones that ask.</param>
        /// <returns>The expression, typed as the type info of the type.</returns>
        internal static string CreateExpression(TypeSpec type, string options)
        {
            if (type.Metadata.Length > 0)
            {
                // The runtime library reads and writes the type from the metadata, with no reflection over its members.
                return "__Create_" + type.PropertyName + "(" + options + ")";
            }

            if (type.Factory.Length > 0)
            {
                // A collection, a dictionary, an enumeration, or a nullable value: every type argument is
                // named here, so nothing is closed over a type at run time, which Native AOT cannot do.
                return type.Factory.Replace("(Options)", "(" + options + ")");
            }

            if (type.Kind == 3)
            {
                return "XmlMetadataServices.CreateEnumInfo<" + type.ClrTypeName + ">(" + options + ")";
            }

            // A built-in value, such as an integer or a string: the runtime library has its converter ready, and
            // a converter of the caller's for the type comes before it.
            return "XmlMetadataServices.CreateBuiltInInfo<" + type.ClrTypeName + ">(" + options + ")";
        }

        /// <summary>
        /// Returns the statement that tells the runtime library what <paramref name="type"/> holds, when it is a
        /// collection or a dictionary.
        /// </summary>
        /// <param name="type">The type spec.</param>
        /// <returns>The statement, or null for a type that is neither, and for an array, whose item type is part of the type.</returns>
        internal static string? ShapeRegistration(TypeSpec type)
        {
            const string collection = "XmlMetadataServices.CreateCollectionInfo<";
            const string dictionary = "XmlMetadataServices.CreateDictionaryInfo<";
            const string options = "(Options)";
            var factory = type.Factory;
            if (!factory.EndsWith(options, StringComparison.Ordinal))
            {
                return null;
            }

            var arguments = factory.Substring(0, factory.Length - options.Length);
            if (arguments.StartsWith(collection, StringComparison.Ordinal))
            {
                return "XmlMetadataServices.RegisterCollection<" + arguments.Substring(collection.Length) + "();";
            }

            return arguments.StartsWith(dictionary, StringComparison.Ordinal)
                ? "XmlMetadataServices.RegisterDictionary<" + arguments.Substring(dictionary.Length) + "();"
                : null;
        }

        /// <summary>
        /// Returns the C# expression for a known naming policy.
        /// </summary>
        /// <param name="policy">The policy value.</param>
        /// <returns>The expression, or null when no policy is set.</returns>
        internal static string? NamingPolicy(int policy)
        {
            return policy switch
            {
                1 => "XmlNamingPolicy.CamelCase",
                2 => "XmlNamingPolicy.SnakeCaseLower",
                3 => "XmlNamingPolicy.SnakeCaseUpper",
                4 => "XmlNamingPolicy.KebabCaseLower",
                5 => "XmlNamingPolicy.KebabCaseUpper",
                6 => "XmlNamingPolicy.PascalCase",
                _ => null,
            };
        }

        /// <summary>
        /// Escapes a string for a C# literal.
        /// </summary>
        /// <param name="value">The value.</param>
        /// <returns>The escaped value.</returns>
        internal static string Escape(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        #endregion

    }

}

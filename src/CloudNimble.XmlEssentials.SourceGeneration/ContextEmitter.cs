using System.Text;

namespace CloudNimble.XmlEssentials.SourceGeneration
{

    /// <summary>
    /// Emits a generated <c>XmlSerializerContext</c> partial class.
    /// </summary>
    internal static class ContextEmitter
    {

        #region Public Methods

        /// <summary>
        /// Emits the generated source for <paramref name="context"/>.
        /// </summary>
        /// <param name="context">The context spec.</param>
        /// <returns>The C# source.</returns>
        internal static string Emit(ContextSpec context)
        {
            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("#pragma warning disable CS8600, CS8601, CS8602, CS8603, CS8604, CS8625");
            builder.AppendLine("using System;");
            builder.AppendLine("using CloudNimble.Text.Xml;");
            builder.AppendLine("using CloudNimble.Text.Xml.Serialization;");
            builder.AppendLine();
            if (!string.IsNullOrEmpty(context.Namespace))
            {
                builder.Append("namespace ").Append(context.Namespace);
                builder.AppendLine();
                builder.AppendLine("{");
                builder.AppendLine();
            }

            var indent = string.IsNullOrEmpty(context.Namespace) ? "" : "    ";
            if (context.EmitInheritance)
            {
                foreach (var type in context.Types)
                {
                    builder.Append(indent).Append("[XmlSerializable(typeof(").Append(type.ClrTypeName).AppendLine("))]");
                }
            }

            builder.Append(indent).Append(context.Accessibility).Append(" partial class ").Append(context.Name);
            if (context.EmitInheritance)
            {
                builder.Append(" : XmlSerializerContext");
            }

            builder.AppendLine();
            builder.Append(indent).AppendLine("{");
            builder.AppendLine();
            builder.Append(indent).Append("    private static readonly ").Append(context.Name).Append(" s_default = new ").Append(context.Name).AppendLine("(null);");
            builder.AppendLine();
            builder.Append(indent).Append("    /// <summary>").AppendLine();
            builder.Append(indent).Append("    /// Gets the default context, seeded from [XmlSourceGenerationOptions] when present.").AppendLine();
            builder.Append(indent).Append("    /// </summary>").AppendLine();
            builder.Append(indent).Append("    public static ").Append(context.Name).AppendLine(" Default => s_default;");
            builder.AppendLine();
            foreach (var type in context.Types)
            {
                builder.Append(indent).Append("    private XmlTypeInfo<").Append(type.ClrTypeName).Append(">? _").Append(type.PropertyName).AppendLine(";");
            }

            builder.AppendLine();
            builder.Append(indent).Append("    /// <summary>").AppendLine();
            builder.Append(indent).Append("    /// Creates a context seeded from [XmlSourceGenerationOptions].").AppendLine();
            builder.Append(indent).Append("    /// </summary>").AppendLine();
            builder.Append(indent).Append("    public ").Append(context.Name).AppendLine("() : this(null)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).Append("    /// <summary>").AppendLine();
            builder.Append(indent).Append("    /// Creates a context with <paramref name=\"options\"/>. Constructor options win over [XmlSourceGenerationOptions].").AppendLine();
            builder.Append(indent).Append("    /// </summary>").AppendLine();
            builder.Append(indent).Append("    /// <param name=\"options\">The options, or null to apply the source-generation seed.</param>").AppendLine();
            builder.Append(indent).Append("    public ").Append(context.Name).AppendLine("(XmlSerializerOptions? options) : base(Apply(options))");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            foreach (var type in context.Types)
            {
                builder.Append(indent).Append("    /// <summary>").AppendLine();
                builder.Append(indent).Append("    /// Gets type info for <see cref=\"").Append(type.ClrTypeName).Append("\"/>.").AppendLine();
                builder.Append(indent).Append("    /// </summary>").AppendLine();
                builder.Append(indent).Append("    public XmlTypeInfo<").Append(type.ClrTypeName).Append("> ").Append(type.PropertyName).AppendLine();
                builder.Append(indent).AppendLine("    {");
                builder.Append(indent).AppendLine("        get");
                builder.Append(indent).AppendLine("        {");
                builder.Append(indent).Append("            return _").Append(type.PropertyName).Append(" ??= ");
                if (type.EmitSerialization)
                {
                    builder.Append("XmlMetadataServices.CreateValueInfo<").Append(type.ClrTypeName).Append(">(Options, new ").Append(type.PropertyName).Append("XmlConverter());");
                }
                else if (type.Kind == 3)
                {
                    builder.Append("XmlMetadataServices.CreateValueInfo<").Append(type.ClrTypeName).Append(">(Options, XmlMetadataServices.CreateEnumConverter<").Append(type.ClrTypeName).Append(">());");
                }
                else
                {
                    builder.Append("(XmlTypeInfo<").Append(type.ClrTypeName).Append(">)(DefaultXmlTypeInfoResolver.Instance.GetTypeInfo(typeof(").Append(type.ClrTypeName).Append("), Options)");
                    builder.Append(" ?? throw new NotSupportedException(\"The type '").Append(type.ClrTypeName).Append("' is not supported.\"))");
                    builder.Append(";");
                }

                builder.AppendLine();
                builder.Append(indent).AppendLine("        }");
                builder.Append(indent).AppendLine("    }");
                builder.AppendLine();
            }

            builder.Append(indent).AppendLine("    /// <inheritdoc />");
            builder.Append(indent).AppendLine("    public override XmlTypeInfo? GetTypeInfo(Type type)");
            builder.Append(indent).AppendLine("    {");
            foreach (var type in context.Types)
            {
                builder.Append(indent).Append("        if (type == typeof(").Append(type.ClrTypeName).Append(")) return ").Append(type.PropertyName).AppendLine(";");
            }

            builder.Append(indent).AppendLine("        return DefaultXmlTypeInfoResolver.Instance.GetTypeInfo(type, Options);");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("    private static XmlSerializerOptions Apply(XmlSerializerOptions? options)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        if (options is not null)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            return options;");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        var seeded = new XmlSerializerOptions();");
            if (context.Options.HasSeed)
            {
                if (context.Options.WriteIndented)
                {
                    builder.Append(indent).AppendLine("        seeded.WriteIndented = true;");
                }

                if (context.Options.OmitXmlDeclaration)
                {
                    builder.Append(indent).AppendLine("        seeded.OmitXmlDeclaration = true;");
                }

                if (!string.IsNullOrEmpty(context.Options.DefaultNamespace))
                {
                    builder.Append(indent).Append("        seeded.DefaultNamespace = \"").Append(Escape(context.Options.DefaultNamespace)).AppendLine("\";");
                }

                EmitNaming(builder, indent, "PropertyNamingPolicy", context.Options.PropertyNamingPolicy);
                EmitNaming(builder, indent, "ElementNamingPolicy", context.Options.ElementNamingPolicy);
                EmitNaming(builder, indent, "AttributeNamingPolicy", context.Options.AttributeNamingPolicy);
                if (context.Options.IncludeFields)
                {
                    builder.Append(indent).AppendLine("        seeded.IncludeFields = true;");
                }
            }

            builder.Append(indent).AppendLine("        return seeded;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            // The type info of a member's type is the same for every object read with the same options, so it
            // is resolved once and kept. The pair is replaced as one object, so a reader never sees the
            // type info of one options instance next to another.
            builder.Append(indent).AppendLine("    private sealed class __Held<T>");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        internal static __Held<T>? Last;");
            builder.Append(indent).AppendLine("        internal readonly XmlSerializerOptions Options;");
            builder.Append(indent).AppendLine("        internal readonly XmlTypeInfo<T> Info;");
            builder.Append(indent).AppendLine("        internal __Held(XmlSerializerOptions options, XmlTypeInfo<T> info)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            Options = options;");
            builder.Append(indent).AppendLine("            Info = info;");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("    private static XmlTypeInfo<T> __GetInfo<T>(XmlSerializerOptions options)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        var held = __Held<T>.Last;");
            builder.Append(indent).AppendLine("        if (held is null || !ReferenceEquals(held.Options, options))");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            held = new __Held<T>(options, (XmlTypeInfo<T>)(options.TypeInfoResolver!.GetTypeInfo(typeof(T), options) ?? throw new NotSupportedException()));");
            builder.Append(indent).AppendLine("            __Held<T>.Last = held;");
            builder.Append(indent).AppendLine("        }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("        return held.Info;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            // An element marked xsi:nil is null for a type that can be null and an error for one that cannot,
            // as the reflection resolver has it. Either form of the element, empty or with an end tag, is consumed.
            builder.Append(indent).AppendLine("    private static T? __ReadNil<T>(ref Utf8XmlReader reader)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        if (default(T) is not null)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            throw new XmlException($\"The element is nil but type '{typeof(T)}' is not nillable.\");");
            builder.Append(indent).AppendLine("        }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("        if (!reader.IsEmptyElement)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            reader.Skip();");
            builder.Append(indent).AppendLine("        }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("        return default;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("    private static string? ReadStringElement(ref Utf8XmlReader reader)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        if (reader.IsEmptyElement)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            return \"\";");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        string? value = \"\";");
            builder.Append(indent).AppendLine("        while (reader.Read())");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            if (reader.TokenType is XmlTokenType.EndElement)");
            builder.Append(indent).AppendLine("            {");
            builder.Append(indent).AppendLine("                break;");
            builder.Append(indent).AppendLine("            }");
            builder.Append(indent).AppendLine("            if (reader.TokenType is XmlTokenType.Text or XmlTokenType.CData)");
            builder.Append(indent).AppendLine("            {");
            builder.Append(indent).AppendLine("                value = reader.GetString();");
            builder.Append(indent).AppendLine("            }");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        return value;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("    private static int ReadInt32Element(ref Utf8XmlReader reader)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        if (reader.IsEmptyElement)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            return 0;");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        var value = 0;");
            builder.Append(indent).AppendLine("        while (reader.Read())");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            if (reader.TokenType is XmlTokenType.EndElement)");
            builder.Append(indent).AppendLine("            {");
            builder.Append(indent).AppendLine("                break;");
            builder.Append(indent).AppendLine("            }");
            builder.Append(indent).AppendLine("            if (reader.TokenType is XmlTokenType.Text or XmlTokenType.CData)");
            builder.Append(indent).AppendLine("            {");
            builder.Append(indent).AppendLine("                value = reader.GetInt32();");
            builder.Append(indent).AppendLine("            }");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        return value;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            builder.Append(indent).AppendLine("    private static decimal ReadDecimalElement(ref Utf8XmlReader reader)");
            builder.Append(indent).AppendLine("    {");
            builder.Append(indent).AppendLine("        if (reader.IsEmptyElement)");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            return 0;");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        decimal value = 0;");
            builder.Append(indent).AppendLine("        while (reader.Read())");
            builder.Append(indent).AppendLine("        {");
            builder.Append(indent).AppendLine("            if (reader.TokenType is XmlTokenType.EndElement)");
            builder.Append(indent).AppendLine("            {");
            builder.Append(indent).AppendLine("                break;");
            builder.Append(indent).AppendLine("            }");
            builder.Append(indent).AppendLine("            if (reader.TokenType is XmlTokenType.Text or XmlTokenType.CData)");
            builder.Append(indent).AppendLine("            {");
            builder.Append(indent).AppendLine("                value = reader.GetDecimal();");
            builder.Append(indent).AppendLine("            }");
            builder.Append(indent).AppendLine("        }");
            builder.Append(indent).AppendLine("        return value;");
            builder.Append(indent).AppendLine("    }");
            builder.AppendLine();
            foreach (var type in context.Types)
            {
                if (type.EmitSerialization)
                {
                    ConverterEmitter.Emit(builder, indent, type);
                }
            }

            builder.Append(indent).AppendLine("}");
            if (!string.IsNullOrEmpty(context.Namespace))
            {
                builder.AppendLine();
                builder.AppendLine("}");
            }

            return builder.ToString();
        }

        #endregion

        #region Private Methods

        /// <summary>
        /// Emits an assignment of a known naming policy when <paramref name="policy"/> is not unspecified.
        /// </summary>
        /// <param name="builder">The source.</param>
        /// <param name="indent">The indent.</param>
        /// <param name="property">The options property name.</param>
        /// <param name="policy">The policy value.</param>
        internal static void EmitNaming(StringBuilder builder, string indent, string property, int policy)
        {
            var value = policy switch
            {
                1 => "XmlNamingPolicy.CamelCase",
                2 => "XmlNamingPolicy.SnakeCaseLower",
                3 => "XmlNamingPolicy.SnakeCaseUpper",
                4 => "XmlNamingPolicy.KebabCaseLower",
                5 => "XmlNamingPolicy.KebabCaseUpper",
                6 => "XmlNamingPolicy.PascalCase",
                _ => null,
            };
            if (value is null)
            {
                return;
            }

            builder.Append(indent).Append("        seeded.").Append(property).Append(" = ").Append(value).AppendLine(";");
        }

        /// <summary>
        /// Escapes a string for a C# literal.
        /// </summary>
        /// <param name="value">The value.</param>
        /// <returns>The escaped value.</returns>
        internal static string Escape(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        #endregion

    }

}

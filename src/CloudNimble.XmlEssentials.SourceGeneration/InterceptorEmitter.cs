using System.Collections.Generic;
using System.Text;

namespace CloudNimble.XmlEssentials.SourceGeneration
{

    /// <summary>
    /// Emits interceptor methods for <c>XmlSerializer</c> calls that pass a value or an input and no options.
    /// </summary>
    internal static class InterceptorEmitter
    {

        #region Public Methods

        /// <summary>
        /// Emits interceptor source for <paramref name="interceptors"/>.
        /// </summary>
        /// <param name="interceptors">The call sites.</param>
        /// <returns>The C# source, or null when there are none.</returns>
        internal static string? Emit(IReadOnlyList<InterceptorSpec> interceptors)
        {
            if (interceptors.Count == 0)
            {
                return null;
            }

            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("using System.Runtime.CompilerServices;");
            builder.AppendLine("using CloudNimble.Text.Xml;");
            builder.AppendLine("using CloudNimble.Text.Xml.Serialization;");
            builder.AppendLine();
            builder.AppendLine("namespace System.Runtime.CompilerServices");
            builder.AppendLine("{");
            builder.AppendLine("    [System.AttributeUsage(System.AttributeTargets.Method, AllowMultiple = true)]");
            builder.AppendLine("    file sealed class InterceptsLocationAttribute : System.Attribute");
            builder.AppendLine("    {");
            builder.AppendLine("        public InterceptsLocationAttribute(int version, string data)");
            builder.AppendLine("        {");
            builder.AppendLine("            _ = version;");
            builder.AppendLine("            _ = data;");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            builder.AppendLine();
            builder.AppendLine("namespace CloudNimble.Text.Xml.Generated");
            builder.AppendLine("{");
            builder.AppendLine("    file static class XmlSerializerInterceptors");
            builder.AppendLine("    {");
            var index = 0;
            foreach (var interceptor in interceptors)
            {
                // The signature is the intercepted method's own. Only a call that passes no options is
                // intercepted, so the options parameter is always null here and the context's own are used.
                var name = interceptor.IsDeserialize ? "Deserialize" : "Serialize";
                builder.Append("        [InterceptsLocation(").Append(interceptor.Version).Append(", \"").Append(interceptor.Data).AppendLine("\")]");
                builder.Append("        public static ").Append(interceptor.ReturnTypeName).Append(' ').Append(name).Append(index).Append('(');
                builder.Append(interceptor.InputModifier).Append(interceptor.InputTypeName).AppendLine(" input, XmlSerializerOptions? options = null)");
                builder.AppendLine("        {");
                builder.AppendLine("            _ = options;");
                builder.Append("            return XmlSerializer.").Append(name).Append('(').Append(interceptor.InputModifier).Append("input, ");
                builder.Append(interceptor.ContextTypeName).Append(".Default.").Append(interceptor.PropertyName).AppendLine(");");
                builder.AppendLine("        }");
                builder.AppendLine();
                index++;
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        #endregion

    }

}
